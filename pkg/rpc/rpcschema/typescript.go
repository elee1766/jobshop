package rpcschema

import (
	"fmt"
	"reflect"
	"slices"
	"strings"

	"github.com/elee1766/jobshop/pkg/rpc"
)

// TypeScript returns desk-plugin.d.ts: the plugin api with RPC method
// params and results typed from rpc.Specs. head is the hand-written part
// (the api object, slots, contexts), placed before the generated types.
func TypeScript(head string) string {
	g := tsGen{seen: map[reflect.Type]string{}, names: map[string]reflect.Type{}}
	// Types the head names that no method returns.
	for _, t := range []reflect.Type{reflect.TypeFor[rpc.Event](), reflect.TypeFor[rpc.ArtifactShowResult]()} {
		g.ref(t)
	}
	var methods strings.Builder
	for _, m := range rpc.Methods() {
		s := rpc.Specs[m]
		res := "Record<string, never>"
		if s.Result != nil {
			res = g.ref(reflect.TypeOf(s.Result))
		}
		fmt.Fprintf(&methods, "  %q: { params: %s; result: %s };\n", m, g.ref(reflect.TypeOf(s.Params)), res)
	}
	var b strings.Builder
	b.WriteString("// Code generated by go run ./pkg/rpc/rpcschema/cmd/deskgen. DO NOT EDIT.\n")
	b.WriteString("// Desk plugin API (#542). See docs/desk-plugins.md.\n\n")
	b.WriteString(head)
	b.WriteString("\n/** Admin RPC methods by name: api.call(method, params) resolves to result. */\nexport interface RpcMethods {\n")
	b.WriteString(methods.String())
	b.WriteString("}\n")
	names := make([]string, 0, len(g.decls))
	for n := range g.decls {
		names = append(names, n)
	}
	slices.Sort(names)
	for _, n := range names {
		b.WriteString("\n")
		b.WriteString(g.decls[n])
	}
	return b.String()
}

type tsGen struct {
	seen  map[reflect.Type]string
	names map[string]reflect.Type
	decls map[string]string
}

// name picks a TypeScript name for a named Go type: the bare name, or
// the package-qualified one when two packages share it.
func (g *tsGen) name(t reflect.Type) string {
	if n, ok := g.seen[t]; ok {
		return n
	}
	n := t.Name()
	if o, ok := g.names[n]; ok && o != t {
		pkg := t.PkgPath()
		pkg = pkg[strings.LastIndex(pkg, "/")+1:]
		n = strings.ToUpper(pkg[:1]) + pkg[1:] + n
	}
	g.names[n] = t
	g.seen[t] = n
	return n
}

func (g *tsGen) ref(t reflect.Type) string {
	switch {
	case t == rawType:
		return "unknown"
	case t == timeType:
		return "string"
	case t == durationType:
		return "number"
	case t.Kind() != reflect.Struct && t.Implements(textType):
		return "string"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return g.ref(t.Elem())
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			return "string"
		}
		e := g.ref(t.Elem())
		if strings.ContainsAny(e, " |") {
			e = "(" + e + ")"
		}
		return e + "[]"
	case reflect.Map:
		return "Record<" + g.ref(t.Key()) + ", " + g.ref(t.Elem()) + ">"
	case reflect.Interface:
		return "unknown"
	case reflect.Struct:
		if t.Name() == "" {
			return g.object(t, "")
		}
		if t.NumField() == 0 {
			return "Record<string, never>"
		}
		if _, ok := g.seen[t]; !ok {
			n := g.name(t)
			if g.decls == nil {
				g.decls = map[string]string{}
			}
			g.decls[n] = "" // placeholder against recursion
			g.decls[n] = "export interface " + n + " " + g.object(t, "") + "\n"
		}
		return g.seen[t]
	}
	return "unknown"
}

func (g *tsGen) object(t reflect.Type, indent string) string {
	var b strings.Builder
	b.WriteString("{\n")
	for _, f := range fields(t) {
		opt := ""
		if f.optional {
			opt = "?"
		}
		key := f.name
		if !tsIdent(key) {
			key = fmt.Sprintf("%q", key)
		}
		fmt.Fprintf(&b, "%s  %s%s: %s;\n", indent, key, opt, g.ref(f.typ))
	}
	b.WriteString(indent + "}")
	return b.String()
}

func tsIdent(s string) bool {
	for i, r := range s {
		if r != '_' && r != '$' && (r < 'a' || r > 'z') && (r < 'A' || r > 'Z') && (i == 0 || r < '0' || r > '9') {
			return false
		}
	}
	return s != ""
}
