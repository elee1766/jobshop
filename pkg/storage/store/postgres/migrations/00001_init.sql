CREATE TABLE tickets (
  id           TEXT PRIMARY KEY,
  project      TEXT NOT NULL,
  kind         TEXT NOT NULL,
  title        TEXT NOT NULL DEFAULT '',
  body         TEXT NOT NULL DEFAULT '',
  status       TEXT NOT NULL DEFAULT 'open'
               CHECK (status IN ('open','in_progress','closed')),
  resolution   TEXT NOT NULL DEFAULT '',
  priority     BIGINT NOT NULL DEFAULT 2,
  pool         TEXT NOT NULL DEFAULT '',
  holder       TEXT NOT NULL DEFAULT '',
  lease_until  BIGINT NOT NULL DEFAULT 0,
  fence        BIGINT NOT NULL DEFAULT 0,
  parent_id    TEXT REFERENCES tickets(id),
  defer_until  BIGINT NOT NULL DEFAULT 0,
  ephemeral    BIGINT NOT NULL DEFAULT 0,
  fields       TEXT NOT NULL DEFAULT '{}',
  meta         TEXT NOT NULL DEFAULT '{}',
  revision     BIGINT NOT NULL DEFAULT 0,
  created_by   TEXT NOT NULL DEFAULT '',
  created_at   BIGINT NOT NULL,
  updated_at   BIGINT NOT NULL,
  closed_at    BIGINT NOT NULL DEFAULT 0,
  f_key        TEXT,
  f_to         TEXT,
  f_state      TEXT,
  f_workflow   TEXT,
  f_index      BIGINT,
  f_waiting    BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX tickets_queue  ON tickets(project, pool, status, priority, created_at);
CREATE INDEX tickets_holder ON tickets(holder) WHERE holder <> '';
CREATE INDEX tickets_lease  ON tickets(lease_until) WHERE status = 'in_progress';
CREATE INDEX tickets_parent ON tickets(parent_id);
CREATE INDEX tickets_kind   ON tickets(kind, status);
CREATE INDEX tickets_message_to ON tickets(f_to) WHERE kind = 'message';
CREATE UNIQUE INDEX tickets_session_key ON tickets(f_key)
  WHERE kind = 'session' AND status <> 'closed' AND f_key IS NOT NULL;
CREATE INDEX tickets_run_key ON tickets(f_key, f_workflow)
  WHERE kind = 'run' AND status <> 'closed';
CREATE INDEX tickets_run_state ON tickets(f_state) WHERE kind = 'run';
CREATE INDEX tickets_children ON tickets(parent_id, f_index);

CREATE TABLE edges (
  from_id    TEXT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  to_id      TEXT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  kind       TEXT NOT NULL CHECK (kind IN ('blocks','waits_for','tracks')),
  created_at BIGINT NOT NULL,
  PRIMARY KEY (from_id, to_id, kind)
);
CREATE INDEX edges_to ON edges(to_id, kind);

CREATE TABLE labels (
  ticket_id TEXT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  label     TEXT NOT NULL,
  PRIMARY KEY (ticket_id, label)
);
CREATE INDEX labels_label ON labels(label);

CREATE TABLE history (
  seq        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id  TEXT NOT NULL,
  at         BIGINT NOT NULL,
  actor      TEXT NOT NULL,
  op         TEXT NOT NULL,
  revision   BIGINT NOT NULL,
  diff       TEXT NOT NULL DEFAULT '{}'
);
CREATE INDEX history_ticket ON history(ticket_id, seq);

CREATE TABLE comments (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id  TEXT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  author     TEXT NOT NULL,
  body       TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  edited_at  BIGINT NOT NULL DEFAULT 0,
  deleted    BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX comments_ticket ON comments(ticket_id, id);

CREATE TABLE learnings (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind       TEXT NOT NULL CHECK (kind IN ('correction','failure','workaround')),
  summary    TEXT NOT NULL,
  fix        TEXT NOT NULL DEFAULT '',
  scope      TEXT NOT NULL DEFAULT 'global',
  ticket     TEXT NOT NULL DEFAULT '',
  session    TEXT NOT NULL DEFAULT '',
  source     TEXT NOT NULL CHECK (source IN ('agent','controller')),
  status     TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','applied','rejected')),
  created_at BIGINT NOT NULL,
  pr         TEXT NOT NULL DEFAULT '',
  gate       TEXT NOT NULL DEFAULT ''
);
CREATE INDEX learnings_created ON learnings(created_at);
CREATE INDEX learnings_scope ON learnings(scope, created_at);

-- Recall (#265): sqlite uses FTS5; here a table with a generated
-- tsvector. RecallSearch is overridden in queries/overrides.sql.
CREATE TABLE recall (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  body      TEXT NOT NULL,
  kind      TEXT NOT NULL,
  ref       TEXT NOT NULL,
  ticket_id TEXT NOT NULL,
  project   TEXT NOT NULL,
  at        TEXT NOT NULL,
  tsv       tsvector GENERATED ALWAYS AS (to_tsvector('english', body)) STORED
);
CREATE INDEX recall_tsv ON recall USING gin(tsv);
CREATE INDEX recall_ref ON recall(kind, ref);

-- +goose StatementBegin
CREATE FUNCTION recall_comment() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'INSERT' THEN
    DELETE FROM recall WHERE kind = 'comment' AND ref = CAST(OLD.id AS TEXT);
  END IF;
  IF TG_OP <> 'DELETE' AND NEW.deleted = 0 THEN
    INSERT INTO recall (body, kind, ref, ticket_id, project, at)
    SELECT NEW.body, 'comment', CAST(NEW.id AS TEXT), NEW.ticket_id,
           COALESCE((SELECT project FROM tickets WHERE id = NEW.ticket_id), ''),
           CAST(NEW.created_at AS TEXT);
  END IF;
  RETURN NULL;
END $$;
-- +goose StatementEnd
CREATE TRIGGER recall_comment AFTER INSERT OR UPDATE OF body, deleted OR DELETE ON comments
  FOR EACH ROW EXECUTE FUNCTION recall_comment();

-- +goose StatementBegin
CREATE FUNCTION recall_learning() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'INSERT' THEN
    DELETE FROM recall WHERE kind = 'learning' AND ref = CAST(OLD.id AS TEXT);
  END IF;
  IF TG_OP <> 'DELETE' THEN
    INSERT INTO recall (body, kind, ref, ticket_id, project, at)
    SELECT NEW.summary || chr(10) || NEW.fix, 'learning', CAST(NEW.id AS TEXT), NEW.ticket,
           COALESCE((SELECT project FROM tickets WHERE id = NEW.ticket), ''),
           CAST(NEW.created_at AS TEXT);
  END IF;
  RETURN NULL;
END $$;
-- +goose StatementEnd
CREATE TRIGGER recall_learning AFTER INSERT OR UPDATE OF summary, fix OR DELETE ON learnings
  FOR EACH ROW EXECUTE FUNCTION recall_learning();

