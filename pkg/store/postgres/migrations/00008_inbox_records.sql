  created_at, CAST(value->'payload' AS TEXT),
  CASE WHEN value->'admitted' IS NULL OR jsonb_typeof(value->'admitted') = 'null' THEN NULL
    ELSE CAST(value->'admitted' AS TEXT) END,
  state, CAST(value->'hook_results' AS TEXT), holder, lease_until, attempts, updated_at,
  value->>'endpoint', value->>'natural_key'
FROM records WHERE collection = 'inbox';
